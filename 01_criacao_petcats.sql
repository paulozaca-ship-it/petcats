    CONSTRAINT fk_aplic_veterinario FOREIGN KEY (id_funcionario) REFERENCES veterinario (id_funcionario),
    CONSTRAINT ck_aplic_datas CHECK (proxima_dose IS NULL OR proxima_dose > data_aplicacao)
