CREATE TABLE produto_fornecedor (
    id_produto          INT            NOT NULL,
    id_fornecedor       INT            NOT NULL,
    preco_custo         DECIMAL(10,2)  NOT NULL,
    prazo_entrega_dias  SMALLINT       NOT NULL,
    CONSTRAINT pk_produto_fornecedor PRIMARY KEY (id_produto, id_fornecedor),
    CONSTRAINT fk_prodforn_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON DELETE CASCADE,
