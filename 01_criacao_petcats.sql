CREATE TABLE venda (
    id_venda         INT         GENERATED BY DEFAULT AS IDENTITY,
    id_tutor         INT,                       -- 0..1: venda de balcão sem cadastro
    id_funcionario   INT          NOT NULL,
    data             TIMESTAMP     NOT NULL,
    forma_pagamento  VARCHAR(15)  NOT NULL,
    CONSTRAINT pk_venda PRIMARY KEY (id_venda),
    CONSTRAINT fk_venda_tutor       FOREIGN KEY (id_tutor)       REFERENCES tutor (id_tutor),
    CONSTRAINT fk_venda_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_funcionario),
    CONSTRAINT ck_venda_pagamento CHECK (forma_pagamento IN ('dinheiro','pix','debito','credito'))
);

CREATE TABLE item_venda (
    id_item        INT           GENERATED BY DEFAULT AS IDENTITY,
    id_venda       INT            NOT NULL,
    id_produto     INT,
    id_servico     INT,
    quantidade     INT            NOT NULL DEFAULT 1,
    preco_cobrado  DECIMAL(10,2)  NOT NULL,   -- preço histórico praticado na venda
    CONSTRAINT pk_item_venda PRIMARY KEY (id_item),
    CONSTRAINT fk_item_venda   FOREIGN KEY (id_venda)   REFERENCES venda (id_venda) ON DELETE CASCADE,
    CONSTRAINT fk_item_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto),
    CONSTRAINT fk_item_servico FOREIGN KEY (id_servico) REFERENCES servico (id_servico),
    CONSTRAINT ck_item_qtd CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco CHECK (preco_cobrado >= 0),
    -- regra: cada item é produto OU serviço, nunca os dois nem nenhum
    CONSTRAINT ck_item_exclusivo CHECK (
        (id_produto IS NOT NULL AND id_servico IS NULL) OR
        (id_produto IS NULL AND id_servico IS NOT NULL)
    )
);

-- Total da venda calculado (removido de VENDA na 3FN)
CREATE VIEW vw_total_venda AS
SELECT v.id_venda,
       v.data,
       SUM(i.quantidade * i.preco_cobrado) AS valor_total
FROM venda v
JOIN item_venda i ON i.id_venda = v.id_venda
GROUP BY v.id_venda, v.data;
