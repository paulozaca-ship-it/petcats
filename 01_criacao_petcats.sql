-- ---------------------------------------------------------------------
-- 1. TUTORES E PACIENTES
-- ---------------------------------------------------------------------
CREATE TABLE tutor (
    id_tutor      INT          GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(100)  NOT NULL,
    cpf           CHAR(11)      NOT NULL,
    email         VARCHAR(120),
    cep           CHAR(8),
    logradouro    VARCHAR(120),
    numero        VARCHAR(10),
    complemento   VARCHAR(60),
    bairro        VARCHAR(60),
    cidade        VARCHAR(60),
    uf            CHAR(2),
    CONSTRAINT pk_tutor PRIMARY KEY (id_tutor),
    CONSTRAINT uk_tutor_cpf UNIQUE (cpf)
);

CREATE TABLE telefone_tutor (
    id_telefone   INT         GENERATED BY DEFAULT AS IDENTITY,
    id_tutor      INT          NOT NULL,
    tipo          VARCHAR(15)  NOT NULL,
    numero        VARCHAR(15)  NOT NULL,
    CONSTRAINT pk_telefone_tutor PRIMARY KEY (id_telefone),
    CONSTRAINT fk_teltutor_tutor FOREIGN KEY (id_tutor)
        REFERENCES tutor (id_tutor) ON DELETE CASCADE,
    CONSTRAINT ck_teltutor_tipo CHECK (tipo IN ('celular','residencial','comercial'))
);

CREATE TABLE raca (
    id_raca       INT          GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(60)   NOT NULL,
    porte         VARCHAR(10)   NOT NULL,
    observacoes   VARCHAR(255),
    CONSTRAINT pk_raca PRIMARY KEY (id_raca),
    CONSTRAINT uk_raca_nome UNIQUE (nome),
    CONSTRAINT ck_raca_porte CHECK (porte IN ('pequeno','medio','grande'))
);

CREATE TABLE gato (
    id_gato          INT         GENERATED BY DEFAULT AS IDENTITY,
    id_tutor         INT          NOT NULL,
    id_raca          INT          NOT NULL,
    nome             VARCHAR(60)  NOT NULL,
    sexo             CHAR(1)      NOT NULL,
    data_nascimento  DATE,
    padrao_pelagem   VARCHAR(40),
    microchip        VARCHAR(15),
    castrado         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_gato PRIMARY KEY (id_gato),
    CONSTRAINT uk_gato_microchip UNIQUE (microchip),
    CONSTRAINT fk_gato_tutor FOREIGN KEY (id_tutor) REFERENCES tutor (id_tutor),
    CONSTRAINT fk_gato_raca  FOREIGN KEY (id_raca)  REFERENCES raca (id_raca),
    CONSTRAINT ck_gato_sexo CHECK (sexo IN ('M','F'))
);

-- ---------------------------------------------------------------------
-- 2. EQUIPE
-- ---------------------------------------------------------------------
CREATE TABLE funcionario (
    id_funcionario  INT          GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(100)  NOT NULL,
    cargo           VARCHAR(40)   NOT NULL,
    email           VARCHAR(120),
    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT uk_funcionario_email UNIQUE (email)
);

CREATE TABLE telefone_funcionario (
    id_telefone     INT         GENERATED BY DEFAULT AS IDENTITY,
    id_funcionario  INT          NOT NULL,
    tipo            VARCHAR(15)  NOT NULL,
    numero          VARCHAR(15)  NOT NULL,
    CONSTRAINT pk_telefone_funcionario PRIMARY KEY (id_telefone),
    CONSTRAINT fk_telfunc_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES funcionario (id_funcionario) ON DELETE CASCADE,
    CONSTRAINT ck_telfunc_tipo CHECK (tipo IN ('celular','residencial','comercial'))
);

-- Especialização 1:0..1 de FUNCIONARIO (PK também é FK)
CREATE TABLE veterinario (
    id_funcionario  INT          NOT NULL,
    numero_crmv     VARCHAR(10)  NOT NULL,
    uf_crmv         CHAR(2)      NOT NULL,
    CONSTRAINT pk_veterinario PRIMARY KEY (id_funcionario),
    CONSTRAINT uk_veterinario_crmv UNIQUE (numero_crmv, uf_crmv),
    CONSTRAINT fk_vet_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES funcionario (id_funcionario)
);

CREATE TABLE vet_especialidade (
    id_funcionario  INT          NOT NULL,
    especialidade   VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_vet_especialidade PRIMARY KEY (id_funcionario, especialidade),
    CONSTRAINT fk_vetesp_veterinario FOREIGN KEY (id_funcionario)
        REFERENCES veterinario (id_funcionario) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 3. AGENDA, SERVIÇOS E HOSPEDAGEM
-- ---------------------------------------------------------------------
CREATE TABLE servico (
    id_servico   INT           GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(60)    NOT NULL,
    descricao    VARCHAR(255),
    duracao_min  SMALLINT       NOT NULL,
    preco        DECIMAL(10,2)  NOT NULL,
    CONSTRAINT pk_servico PRIMARY KEY (id_servico),
    CONSTRAINT uk_servico_nome UNIQUE (nome),
    CONSTRAINT ck_servico_duracao CHECK (duracao_min > 0),
    CONSTRAINT ck_servico_preco CHECK (preco >= 0)
);

CREATE TABLE agendamento (
    id_agendamento  INT         GENERATED BY DEFAULT AS IDENTITY,
    id_gato         INT          NOT NULL,
    id_funcionario  INT          NOT NULL,
    data            DATE         NOT NULL,
    hora            TIME         NOT NULL,
    status          VARCHAR(15)  NOT NULL DEFAULT 'agendado',
    CONSTRAINT pk_agendamento PRIMARY KEY (id_agendamento),
    CONSTRAINT fk_agend_gato        FOREIGN KEY (id_gato)        REFERENCES gato (id_gato),
    CONSTRAINT fk_agend_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_funcionario),
    CONSTRAINT ck_agend_status CHECK (status IN ('agendado','concluido','cancelado'))
);

CREATE TABLE agendamento_servico (
    id_agendamento  INT            NOT NULL,
    id_servico      INT            NOT NULL,
    preco_cobrado   DECIMAL(10,2)  NOT NULL,
    CONSTRAINT pk_agendamento_servico PRIMARY KEY (id_agendamento, id_servico),
    CONSTRAINT fk_agserv_agendamento FOREIGN KEY (id_agendamento)
        REFERENCES agendamento (id_agendamento) ON DELETE CASCADE,
    CONSTRAINT fk_agserv_servico FOREIGN KEY (id_servico) REFERENCES servico (id_servico),
    CONSTRAINT ck_agserv_preco CHECK (preco_cobrado >= 0)
);

CREATE TABLE quarto (
    id_quarto     INT           GENERATED BY DEFAULT AS IDENTITY,
    numero        VARCHAR(5)     NOT NULL,
    tipo          VARCHAR(20)    NOT NULL,
    valor_diaria  DECIMAL(10,2)  NOT NULL,
    CONSTRAINT pk_quarto PRIMARY KEY (id_quarto),
    CONSTRAINT uk_quarto_numero UNIQUE (numero),
    CONSTRAINT ck_quarto_diaria CHECK (valor_diaria > 0)
);

CREATE TABLE hospedagem (
    id_hospedagem  INT      GENERATED BY DEFAULT AS IDENTITY,
    id_gato        INT       NOT NULL,
    id_quarto      INT       NOT NULL,
    entrada        TIMESTAMP  NOT NULL,
    saida          TIMESTAMP,
    CONSTRAINT pk_hospedagem PRIMARY KEY (id_hospedagem),
    CONSTRAINT fk_hosp_gato   FOREIGN KEY (id_gato)   REFERENCES gato (id_gato),
    CONSTRAINT fk_hosp_quarto FOREIGN KEY (id_quarto) REFERENCES quarto (id_quarto),
    CONSTRAINT ck_hosp_periodo CHECK (saida IS NULL OR saida > entrada)
);

CREATE TABLE ocorrencia_hospedagem (
    id_ocorrencia  INT          GENERATED BY DEFAULT AS IDENTITY,
    id_hospedagem  INT           NOT NULL,
    data_hora      TIMESTAMP      NOT NULL,
    descricao      VARCHAR(255)  NOT NULL,
    CONSTRAINT pk_ocorrencia_hospedagem PRIMARY KEY (id_ocorrencia),
    CONSTRAINT fk_ocor_hospedagem FOREIGN KEY (id_hospedagem)
        REFERENCES hospedagem (id_hospedagem) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 4. ATENDIMENTO CLÍNICO
-- ---------------------------------------------------------------------
CREATE TABLE consulta (
    id_consulta     INT          GENERATED BY DEFAULT AS IDENTITY,
    id_gato         INT           NOT NULL,
    id_funcionario  INT           NOT NULL,   -- veterinário responsável
    data            TIMESTAMP      NOT NULL,
    queixa          VARCHAR(255)  NOT NULL,
    peso_kg         DECIMAL(4,2),
    conduta         TEXT,
    CONSTRAINT pk_consulta PRIMARY KEY (id_consulta),
    CONSTRAINT fk_consulta_gato        FOREIGN KEY (id_gato)        REFERENCES gato (id_gato),
    CONSTRAINT fk_consulta_veterinario FOREIGN KEY (id_funcionario) REFERENCES veterinario (id_funcionario),
    CONSTRAINT ck_consulta_peso CHECK (peso_kg IS NULL OR peso_kg > 0)
);

CREATE TABLE consulta_diagnostico (
    id_consulta  INT           NOT NULL,
    descricao    VARCHAR(150)  NOT NULL,
    CONSTRAINT pk_consulta_diagnostico PRIMARY KEY (id_consulta, descricao),
    CONSTRAINT fk_consdiag_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta) ON DELETE CASCADE
);

CREATE TABLE exame (
    id_exame     INT         GENERATED BY DEFAULT AS IDENTITY,
    id_consulta  INT          NOT NULL,
    tipo         VARCHAR(60)  NOT NULL,
    data         DATE         NOT NULL,
    CONSTRAINT pk_exame PRIMARY KEY (id_exame),
    CONSTRAINT fk_exame_consulta FOREIGN KEY (id_consulta) REFERENCES consulta (id_consulta)
);

CREATE TABLE parametro_exame (
    id_parametro      INT         GENERATED BY DEFAULT AS IDENTITY,
    nome              VARCHAR(60)  NOT NULL,
    unidade           VARCHAR(20)  NOT NULL,
    valor_referencia  VARCHAR(40),
    CONSTRAINT pk_parametro_exame PRIMARY KEY (id_parametro),
    CONSTRAINT uk_parametro_nome UNIQUE (nome)
);

CREATE TABLE resultado_exame (
    id_exame      INT            NOT NULL,
    id_parametro  INT            NOT NULL,
    valor         DECIMAL(10,3)  NOT NULL,
    CONSTRAINT pk_resultado_exame PRIMARY KEY (id_exame, id_parametro),
    CONSTRAINT fk_result_exame FOREIGN KEY (id_exame)
        REFERENCES exame (id_exame) ON DELETE CASCADE,
    CONSTRAINT fk_result_parametro FOREIGN KEY (id_parametro)
        REFERENCES parametro_exame (id_parametro)
);

CREATE TABLE medicamento (
    id_medicamento      INT          GENERATED BY DEFAULT AS IDENTITY,
    nome                VARCHAR(80)   NOT NULL,
    forma_farmaceutica  VARCHAR(30)   NOT NULL,
    concentracao        DECIMAL(8,2),
    unidade             VARCHAR(10),
    CONSTRAINT pk_medicamento PRIMARY KEY (id_medicamento),
    CONSTRAINT uk_medicamento_nome UNIQUE (nome)
);

CREATE TABLE med_principio_ativo (
    id_medicamento   INT          NOT NULL,
    principio_ativo  VARCHAR(60)  NOT NULL,
    concentracao     VARCHAR(30),
    CONSTRAINT pk_med_principio_ativo PRIMARY KEY (id_medicamento, principio_ativo),
    CONSTRAINT fk_medpa_medicamento FOREIGN KEY (id_medicamento)
        REFERENCES medicamento (id_medicamento) ON DELETE CASCADE
);

CREATE TABLE prescricao (
    id_prescricao   INT          GENERATED BY DEFAULT AS IDENTITY,
    id_consulta     INT           NOT NULL,
    id_medicamento  INT           NOT NULL,
    dose_qtd        DECIMAL(6,2)  NOT NULL,
    dose_unidade    VARCHAR(10)   NOT NULL,
    intervalo_h     SMALLINT      NOT NULL,
    duracao_dias    SMALLINT      NOT NULL,
    CONSTRAINT pk_prescricao PRIMARY KEY (id_prescricao),
    CONSTRAINT fk_presc_consulta    FOREIGN KEY (id_consulta)    REFERENCES consulta (id_consulta),
    CONSTRAINT fk_presc_medicamento FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento),
    CONSTRAINT ck_presc_valores CHECK (dose_qtd > 0 AND intervalo_h > 0 AND duracao_dias > 0)
);

CREATE TABLE vacina (
    id_vacina       INT         GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(60)  NOT NULL,
    intervalo_dias  SMALLINT     NOT NULL,
    CONSTRAINT pk_vacina PRIMARY KEY (id_vacina),
    CONSTRAINT uk_vacina_nome UNIQUE (nome),
    CONSTRAINT ck_vacina_intervalo CHECK (intervalo_dias > 0)
);

CREATE TABLE doenca (
    id_doenca  INT         GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(80)  NOT NULL,
    CONSTRAINT pk_doenca PRIMARY KEY (id_doenca),
    CONSTRAINT uk_doenca_nome UNIQUE (nome)
);

CREATE TABLE vacina_doenca (
    id_vacina  INT  NOT NULL,
    id_doenca  INT  NOT NULL,
    CONSTRAINT pk_vacina_doenca PRIMARY KEY (id_vacina, id_doenca),
    CONSTRAINT fk_vacdoe_vacina FOREIGN KEY (id_vacina)
        REFERENCES vacina (id_vacina) ON DELETE CASCADE,
    CONSTRAINT fk_vacdoe_doenca FOREIGN KEY (id_doenca)
        REFERENCES doenca (id_doenca) ON DELETE CASCADE
);

CREATE TABLE lote_vacina (
    id_lote      INT         GENERATED BY DEFAULT AS IDENTITY,
    id_vacina    INT          NOT NULL,
    numero_lote  VARCHAR(20)  NOT NULL,
    validade     DATE         NOT NULL,
    fabricante   VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_lote_vacina PRIMARY KEY (id_lote),
    CONSTRAINT uk_lotevac_numero UNIQUE (id_vacina, numero_lote),
    CONSTRAINT fk_lotevac_vacina FOREIGN KEY (id_vacina) REFERENCES vacina (id_vacina)
