-- =====================================================================
-- Petcats - Script de criação do banco (DDL)
-- SGBD: PostgreSQL 16+ (testado no 19) | Cliente: psql
-- Modelo lógico normalizado até a 3FN (37 tabelas + 1 view)
-- Exceção documentada: endereço completo mantido em TUTOR (CEP)
-- Pré-requisito: banco "petcats" criado e conexão aberta nele
