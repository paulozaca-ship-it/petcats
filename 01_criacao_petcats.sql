CREATE TABLE aplicacao_vacina (
    id_aplicacao    INT  GENERATED BY DEFAULT AS IDENTITY,
    id_gato         INT   NOT NULL,
    id_lote         INT   NOT NULL,
    id_funcionario  INT   NOT NULL,   -- veterinário que aplicou
